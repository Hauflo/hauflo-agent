// node scripts/build.mjs [--check]  → generates tokens/canon (gen.mjs) and bundles src/index.js into ONE file:
// agent/custom_components/hauflo/www/hauflo-cards-v5.js (committed). --check: fails if the committed file is stale or over budget.
import { existsSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { generate } from "./gen.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "../custom_components/hauflo/www/hauflo-cards-v5.js");
const BUDGET = JSON.parse(readFileSync(join(ROOT, "canon/kit.json"), "utf8")).budget_bytes;

const esbuildPath = () => {
  for (const base of [resolve(ROOT, "../../backend"), resolve(ROOT, "../../../../../backend"), process.env.ESBUILD_FROM].filter(Boolean)) {
    const p = join(base, "node_modules/esbuild");
    if (existsSync(p)) return p;
  }
  throw new Error("esbuild not found (backend/node_modules/esbuild)");
};

export async function bundle() {
  generate();
  const { build } = createRequire(import.meta.url)(esbuildPath());
  const r = await build({
    entryPoints: [join(ROOT, "src/index.js")], bundle: true, format: "esm", target: "es2020", minify: true, legalComments: "none",
    write: false, loader: { ".json": "json" }, banner: { js: "// Hauflo cards v5 — GENERATED by agent/cards-v5/scripts/build.mjs from agent/cards-v5/src. Do not edit." },
  });
  return r.outputFiles[0].text;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await bundle();
  const size = Buffer.byteLength(text);
  if (size > BUDGET) throw new Error(`bundle ${size} B is over the budget ${BUDGET} B (canon/kit.json budget_bytes)`);
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) throw new Error("hauflo-cards-v5.js is stale: run node agent/cards-v5/scripts/build.mjs");
    console.log("up to date,", size, "B of", BUDGET);
  } else {
    writeFileSync(OUT, text);
    console.log("built", OUT, size, "B of", BUDGET);
  }
}
