// Generates src/gen/{tokens,canon}.js from the canon data in ../canon (the ONE source of sizes, colours, timings).
// Components never carry literal colours/sizes/timings: they read --hf-* (tokens.js) and CANON (canon.js).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(ROOT, "canon", p), "utf8"));

/** rem → calc(x * var(--hf-root)) so the system text size scales every font through one root. */
const remToRoot = (v) => String(v).replace(/(-?[0-9.]+)rem\b/g, (_, n) => `calc(${n} * var(--hf-root, 1rem))`);

export function tokensCss({ schema = read("themes/schema.json"), theme = read("themes/atelier.json"), large = read("themes/overlays/large.json"), kit = read("kit.json") } = {}) {
  const prim = theme.primitives || {};
  const ref = (v) => String(v).replace(/\{([a-z0-9-]+)\}/g, (_, k) => prim[k] ?? `var(--hf-${k})`);
  const decl = (o) => Object.entries(o).map(([k, v]) => `--hf-${k}:${k === "root" ? ref(v) : remToRoot(ref(v))}`).join(";");
  const base = {};
  for (const [k, t] of Object.entries(schema.tokens)) base[k] = t.default ?? t.bridge;
  for (const [k, t] of Object.entries(schema.modeTokens)) base[k] = t.bridge;
  Object.assign(base, kit.tokens);
  // roles: every mode token that a theme gives a -text pair (accent, state-*) — R-text / R-tint / R-glow (schema.roleDerived)
  const roles = Object.keys(schema.modeTokens).filter((k) => k === "accent" || /^state-/.test(k));
  const der = schema.roleDerived;
  for (const r of roles) {
    if (!(r + "-text" in base)) base[r + "-text"] = `var(--hf-${r})`;
    for (const kind of ["tint", "glow"]) base[`${r}-${kind}`] = der[kind].derive.replace(/\{R\}/g, r);
  }
  // In a shadow root an attribute on the host is :host([…]) — «:host[…]» is invalid and drops the whole rule.
  const host = (sel) => (sel ? `:host(${sel}),.hf-host${sel}` : ":host,.hf-host");
  return [
    `${host("")}{${decl(base)}}`,
    `${host("[data-hf-theme=atelier]")}{${decl(theme.tokens || {})}}`,
    ...theme.modes.map((m) => `${host(`[data-hf-theme=atelier][data-mode=${m}]`)}{${decl(theme[m] || {})}}`),
    `${host("[data-hf-large]")}{${decl(large.tokens || {})}}`,
  ].join("\n");
}

export function canonData() {
  const g = read("gestures.json"), s = read("sizes.json"), kit = read("kit.json"), large = read("themes/overlays/large.json");
  const strip = (o) => JSON.parse(JSON.stringify(o, (k, v) => (k.startsWith("$") || k === "is" || k === "does" || k === "doc" ? undefined : v)));
  return {
    timing: g.timing_ms,
    dragAxisRatio: g.v2.drag_axis_ratio,
    sizes: strip({ variants: s.variants, variants_unfixed: s.variants_unfixed, modifiers: s.modifiers, grid: { row_px: s.grid.row_px, gap_px: s.grid.gap_px, columns: s.grid.columns, snap_below_view: s.grid.snap_below_view } }),
    num: { steps_px: s.fit.num.steps_px, start: s.fit.num.start },
    textScale: { haVar: s.text_scale.ha_var, min: s.v5.text_scale.min, max: s.v5.text_scale.max, largeFrom: s.text_scale.large_auto_from, largeMin: large.text_scale_min },
    badgePriority: s.v5.badge.priority,
    cards: kit.cards, remote: kit.remote, light: kit.light, climate: kit.climate, cover: kit.cover, device: kit.device, remoteDevice: kit.remote_device, graph: kit.graph, room: kit.room, status: kit.status, hero: kit.hero, leaks: kit.leaks, security: kit.security, entity: kit.entity,
  };
}

export function generate() {
  const out = join(ROOT, "src", "gen");
  mkdirSync(out, { recursive: true });
  const head = "// GENERATED by scripts/gen.mjs from ../canon — do not edit.\n";
  writeFileSync(join(out, "tokens.js"), `${head}export const TOKENS_CSS = ${JSON.stringify(tokensCss())};\n`);
  const icons = read("icons.json"); delete icons.$comment;
  writeFileSync(join(out, "icons.js"), `${head}export const ICONS = ${JSON.stringify(icons)};\n`);
  writeFileSync(join(out, "canon.js"), `${head}export const CANON = ${JSON.stringify(canonData(), null, 1)};\n`);
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) console.log("generated", generate());
